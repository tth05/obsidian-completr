import { watch } from "node:fs";
import { builtinModules } from "node:module";
import { parseArgs } from "node:util";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

const BANNER = `/*
THIS IS A GENERATED/BUNDLED FILE
if you want to view the source, please visit the github repository of this plugin
*/
`;

export async function build(opts: { production: boolean; outdir?: string }) {
    const outdir = opts.outdir ?? root;
    const result = await Bun.build({
        entrypoints: [`${root}/src/main.ts`],
        outdir,
        naming: "main.js",
        format: "cjs",
        target: "browser",
        banner: BANNER,
        minify: opts.production,
        sourcemap: opts.production ? "none" : "inline",
        external: [
            "obsidian",
            "electron",
            "@codemirror/*",
            "@lezer/*",
            ...builtinModules,
            ...builtinModules.map((m) => `node:${m}`),
        ],
    });
    if (!result.success) {
        for (const log of result.logs) console.error(log);
        throw new Error("Build failed");
    }

    if (opts.outdir) {
        await Bun.write(`${outdir}/manifest.json`, Bun.file(`${root}/manifest.json`));
        await Bun.write(`${outdir}/styles.css`, Bun.file(`${root}/styles.css`));
    }
}

if (import.meta.main) {
    const { values: args } = parseArgs({
        options: {
            production: { type: "boolean", default: false },
            watch: { type: "boolean", default: false },
            // Directory to write main.js/manifest.json/styles.css into (used by the e2e harness).
            outdir: { type: "string" },
        },
    });
    const rebuild = async () => {
        const start = performance.now();
        try {
            await build({ production: args.production, outdir: args.outdir });
            console.log(`Built in ${(performance.now() - start).toFixed(0)}ms`);
        } catch (e) {
            console.error(e);
            if (!args.watch) process.exit(1);
        }
    };

    await rebuild();
    if (args.watch) {
        let timer: Timer | undefined;
        watch(`${root}/src`, { recursive: true }, () => {
            clearTimeout(timer);
            timer = setTimeout(() => void rebuild(), 50);
        });
        console.log("Watching src/ for changes...");
    }
}
